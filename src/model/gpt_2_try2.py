"""
Full definition of a GPT Language Model, training it using pre-tokenized binary data.
Tokenized binary files (e.g. tokenized_data/train.bin and tokenized_data/val.bin)
are assumed to be generated by a separate tokenization script.
References:
1) Official GPT-2 TensorFlow implementation:
   https://github.com/openai/gpt-2/blob/master/src/model.py
2) Hugging Face/transformers PyTorch implementation:
   https://github.com/huggingface/transformers/blob/main/src/transformers/models/gpt2/modeling_gpt2.py
"""

